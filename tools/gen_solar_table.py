#!/usr/bin/env python3
"""Generate the solar declination / equation-of-time table.

Offline, no network, Python stdlib only. One entry per date for 2028
(a leap year, so all 366 date slots are real); the watch indexes it by
month/day, never by year.

Model: NOAA low-precision solar position, evaluated at 00:00 UTC of each day.

  --write   write src/c/solar_table.h
  --check   exit 0 if src/c/solar_table.h matches a fresh generation
"""
import math
import sys
from datetime import date, timedelta

SOLAR_TABLE_DAYS = 366
TABLE_YEAR = 2028
# unix seconds of TABLE_YEAR-01-01 00:00 UTC
EPOCH_UNIX = (date(TABLE_YEAR, 1, 1) - date(1970, 1, 1)).days * 86400

HEADER = """\
/* Generated by tools/gen_solar_table.py -- do not hand-edit.
 * NOAA low-precision solar position at 00:00 UTC for each date of %d.
 * Indexed by date (month/day); index 59 is Feb 29.
 * Declination in centidegrees, equation of time in centiminutes.
 */
#define SOLAR_TABLE_DAYS %d
""" % (TABLE_YEAR, SOLAR_TABLE_DAYS)


def date_of_index(day_index):
    return date(TABLE_YEAR, 1, 1) + timedelta(days=day_index)


def wrap180(deg):
    return (deg + 180.0) % 360.0 - 180.0


def solar_day(day_index):
    """Return (decl_cdeg, eot_cmin) for 00:00 UTC of the given day index."""
    unix_seconds = EPOCH_UNIX + day_index * 86400
    jd = unix_seconds / 86400.0 + 2440587.5
    n = jd - 2451545.0
    L = (280.460 + 0.9856474 * n) % 360.0
    g = math.radians((357.528 + 0.9856003 * n) % 360.0)
    lam = math.radians((L + 1.915 * math.sin(g) + 0.020 * math.sin(2 * g)) % 360.0)
    eps = math.radians(23.439 - 0.0000004 * n)
    decl = math.degrees(math.asin(math.sin(eps) * math.sin(lam)))
    ra = math.degrees(math.atan2(math.cos(eps) * math.sin(lam), math.cos(lam)))
    eot = 4.0 * wrap180(L - 0.0057183 - ra)  # minutes
    return round(decl * 100), round(eot * 100)


def generate():
    decl, eot = [], []
    for i in range(SOLAR_TABLE_DAYS):
        d, e = solar_day(i)
        decl.append(d)
        eot.append(e)
    lines = [HEADER.rstrip()]
    for name, values in (("k_decl_cdeg", decl), ("k_eot_cmin", eot)):
        rows = [", ".join(str(v) for v in values[i:i + 12])
                for i in range(0, len(values), 12)]
        lines.append("static const int16_t %s[SOLAR_TABLE_DAYS] = {" % name)
        lines.extend(r + "," for r in rows)
        lines.append("};")
    lines.append("")
    return "\n".join(lines)


def main():
    path = "src/c/solar_table.h"
    text = generate()
    if "--write" in sys.argv:
        with open(path, "w") as f:
            f.write(text)
        print("wrote", path)
    elif "--check" in sys.argv:
        try:
            with open(path) as f:
                current = f.read()
        except FileNotFoundError:
            print("FAIL: %s missing; run --write" % path)
            return 1
        if current != text:
            print("FAIL: %s is stale; run --write" % path)
            return 1
        print("solar_table.h is fresh")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
